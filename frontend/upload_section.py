def _start_processing():
    """Save the chosen files under a new upload id, then switch to step 2."""
    upload_id = up.new_upload_id()
    files = {}
    used_names = set()

    def store(source, subfolder):
        origin, item = source

        if origin == "demo":
            return str(item)

        name = Path(item.name).name
        stem, suffix = Path(name).stem, Path(name).suffix
        counter = 1

        while f"{subfolder}/{name}" in used_names:
            counter += 1
            name = f"{stem}_{counter}{suffix}"

        used_names.add(f"{subfolder}/{name}")
        return str(up.save_uploaded_file(upload_id, name, item.getvalue(), subfolder))

    for kind in ("quiz_responses", "quiz_questions", "student_comments", "video_topics", "video", "transcript"):
        chosen = _selected(kind)

        if chosen:
            files[kind] = store(chosen[0], "raw")

    for kind, subfolder in (("documents", "documents"), ("images", "images")):
        chosen = _selected(kind)

        if chosen:
            files[kind] = [store(source, subfolder) for source in chosen]

    describe = bool(st.session_state.get("up_opt_describe", True)) and _gemini_ready()

    st.session_state["up_pending"] = {
        "upload_id": upload_id,
        "files": files,
        "options": {
            "describe_images": describe,
            "max_images": MAX_IMAGES,
            "frame_every_seconds": int(st.session_state.get("up_opt_interval", 10)),
            "extract_frames": bool(st.session_state.get("up_opt_extract", False)),
        },
        "saved": sum(len(value) if isinstance(value, list) else 1 for value in files.values()),
    }
    st.session_state["up_step"] = 2
    st.session_state["up_run"] = True
    st.session_state.pop("up_error", None)


