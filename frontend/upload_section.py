def _report_topics(report):
    """[(topic_id, topic_name, result or None, error or None)] for any scope."""
    data = report["data"]

    if report["scope"] == SCOPE_TOPIC:
        return [(data["topic_id"], data["topic_name"], data, None)]

    return [
        (topic["topic_id"], topic["topic_name"], topic.get("result"), topic.get("error"))
        for topic in data["topics"]
    ]


def report_markdown(upload, report):
    lines = [
        "# Course report",
        "",
        f"- Upload: {upload['upload_id']}",
        f"- Generated: {report['generated_at']}",
        f"- Report type: {report['scope']}",
        "",
        f"> {AI_DISCLAIMER[0]} {AI_DISCLAIMER[1]}",
        "",
    ]

    for topic_id, topic_name, result, error in _report_topics(report):
        lines += [f"## {topic_name} ({topic_id})", ""]

        if error:
            lines += [f"Report failed: {error}", ""]
            continue

        lines += [f"**Question:** {result['question']}", "", result["answer"].strip(), "", "### Evidence", ""]

        for source in result.get("sources", []):
            excerpt = " ".join(str(source.get("text", "")).split())[:400]
            lines.append(
                f"- **{source.get('reference')}** · {source.get('modality')} · "
                f"{source.get('source_id')} · {source.get('source_location')}\n  > {excerpt}"
            )

        lines.append("")

    return "\n".join(lines)


def _upload_topic_frames(upload):
    files = upload.get("files", {})
    comments = _read_upload_csv(files["student_comments"]) if files.get("student_comments") else None
    topics = _read_upload_csv(files["video_topics"]) if files.get("video_topics") else None
    return comments, topics


def _open_upload_dialog(upload, summary, statuses):
    topic_id = st.session_state.pop("up_quick_view_topic", None)

    if topic_id is None or topic_id not in set(summary["topic_id"]):
        return

    row = summary[summary["topic_id"] == topic_id].iloc[0]
    comments, topics = _upload_topic_frames(upload)
    topic_comments = (
        comments[comments["topic_id"].astype(str) == topic_id] if comments is not None
        else pd.DataFrame(columns=["comment_id", "comment_type", "comment_text"])
    )
    segment = None

    if topics is not None:
        match = topics[topics["topic_id"].astype(str) == topic_id]

        if not match.empty:
            start = match.iloc[0]["approx_start_time"]
            segment = {
                "start": start,
                "end": match.iloc[0]["approx_end_time"],
                "start_seconds": int(up._to_seconds(start)),
            }

    video = upload.get("files", {}).get("video")
    ui.topic_dialog(row, statuses[topic_id], topic_comments, segment, video, _up_select, _up_ask)


def _render_review_form(upload, report, user, user_can_review):
    topics = [(t_id, name, result) for t_id, name, result, error in _report_topics(report) if result]

    if not topics:
        return

    with st.container(border=True, key="lp_card_up_review"):
        ui.render(ui.card_title("Save for educator review"))

        with st.form("up_review_form"):
            names = {t_id: name for t_id, name, _ in topics}

            if len(topics) > 1:
                topic_id = st.selectbox("Topic", list(names), format_func=lambda t: names[t], key="up_review_topic")
            else:
                topic_id = topics[0][0]

            decision = st.segmented_control(
                "Review decision",
                ["Approve", "Request changes", "Reject"],
                default="Approve",
                required=True,
                key="up_chips_review_decision",
            )
            notes = st.text_area("Reviewer comments", placeholder="Explain your decision...", key="up_review_notes")
            submitted = st.form_submit_button("Save Review Decision", type="primary")

            if submitted:
                result = next(result for t_id, _, result in topics if t_id == topic_id)
                sources = result.get("sources", [])

                if not user_can_review:
                    st.error("Your account cannot save review decisions.")

                elif decision != "Approve" and not (notes or "").strip():
                    st.warning(
                        "Please explain why changes are needed "
                        "or why the report was rejected."
                    )

                elif not sources:
                    st.warning("Cannot review a report without evidence.")

                else:
                    review_id = save_review(
                        topic_id=f"upload:{topic_id}",
                        question=result["question"],
                        answer=result["answer"],
                        sources=sources,
                        decision=decision,
                        notes=notes,
                        reviewer=user["username"],
                    )
                    st.success(f"Review #{review_id} saved successfully.")


def render_results(user, user_can_review):
    upload = st.session_state.get("upload")

    if not upload or not upload.get("report"):
        return

    report, manifest, summary = upload["report"], upload["manifest"], upload["summary_df"]
    counts = manifest.get("counts", {})

    # ---- header card ----
    chips = []

    if summary is not None:
        chips.append(f"📊 {int(summary['total_attempts'].sum()):,} quiz attempts")

    for modality, icon, label in MODALITY_CHIPS:
        if counts.get(modality):
            chips.append(f"{icon} {counts[modality]:,} {label}")

    created = ui.format_timestamp(manifest.get("created_at", ""))
    ui.render(
        '<div class="up-report-head" id="upload-report">'
        '<div class="up-report-title" role="heading" aria-level="2">Your course report</div>'
        f'<div class="up-report-meta">Upload {ui._esc(upload["upload_id"])} · created {ui._esc(created)} UTC · '
        f'{ui._esc(report["scope"])}</div>'
        '<div class="up-report-chips">'
        + "".join(f'<span class="up-chip">{ui._esc(chip)}</span>' for chip in chips)
        + "</div></div>"
    )

    # ---- KPIs ----
    if summary is not None:
        col1, col2, col3 = st.columns(3)
        col1.metric("Quiz Attempts", f"{int(summary['total_attempts'].sum()):,}")
        col2.metric("Student Comments", f"{counts.get('learner_comment', 0):,}")
        col3.metric("Topics Analysed", len(summary))

        # ---- uploaded topics as interactive cards ----
        max_rate = summary["incorrect_rate_pct"].max()
        statuses = {
            str(row.topic_id): ui.topic_status(row.incorrect_rate_pct, max_rate)
            for row in summary.itertuples()
        }
        selected = st.session_state.get("up_selected_topic")
        ui.render(ui.section_title("Uploaded topics"))

        for row_start in range(0, len(summary), 4):
            columns = st.columns(4)

            for column, (index, row) in zip(columns, summary.iloc[row_start:row_start + 4].iterrows()):
                with column:
                    ui.topic_card(
                        row, "upload", str(row["topic_id"]) == selected,
                        status=statuses[str(row["topic_id"])], seed=index,
                        on_select=_up_select, on_quick_view=_up_quick_view,
                        on_explore=_up_explore, on_ask=_up_ask,
                    )

        _open_upload_dialog(upload, summary, statuses)

    # ---- the report ----
    ui.render(ui.section_title("AI report"))
    ui.render(ui.info_strip(*AI_DISCLAIMER))
    topics = _report_topics(report)

    def show(index, topic_id, topic_name, result, error):
        with st.container(border=True, key=f"lp_card_up_answer_{index}"):
            if error:
                st.error(f"The report for {topic_name} could not be generated. {_friendly_ai_error(error)}")

                # Gemini is sometimes temporarily unavailable (503): retry
                # just this topic instead of the whole overview
                if st.button("Retry this topic", key=f"up_retry_topic_{index}", type="primary"):
                    try:
                        with st.spinner(f"Generating the report for {topic_name}…"):
                            retried = up.generate_upload_report(
                                upload["upload_id"], summary, "topic", topic_id=topic_id
                            )
                    except Exception as retry_error:
                        st.error(f"Still not available. {_friendly_ai_error(retry_error)}")
                        return

                    entry = report["data"]["topics"][index]
                    entry.pop("error", None)
                    entry["result"] = retried
                    st.rerun()

                return

            ui.render(ui.card_title(topic_name))
            st.caption(result["question"])
            st.markdown(result["answer"])
            ui.cited_evidence_pills(
                "upload", result["answer"], result.get("sources", []),
                key_suffix=f"-t{index}", extra_state={"up_chips_ev_topic": topic_id},
            )

    if len(topics) > 1:
        tabs = st.tabs([name for _, name, _, _ in topics])

        for index, (tab, topic) in enumerate(zip(tabs, topics)):
            with tab:
                show(index, *topic)
    else:
        show(0, *topics[0])

    # ---- evidence ----
    with_results = [(t_id, name, result) for t_id, name, result, error in topics if result and result.get("sources")]

    if with_results:
        ui.render(ui.section_title("Evidence"))
        names = {t_id: name for t_id, name, _ in with_results}

        if st.session_state.get("up_chips_ev_topic") not in names:
            st.session_state["up_chips_ev_topic"] = with_results[0][0]

        if len(with_results) > 1:
            st.segmented_control("Evidence for", list(names), format_func=lambda t: names[t],
                                 required=True, key="up_chips_ev_topic")

        topic_id = st.session_state["up_chips_ev_topic"]
        result = next(result for t_id, _, result in with_results if t_id == topic_id)
        comments, _topics = _upload_topic_frames(upload)
        comment_types = (
            dict(zip(comments["comment_id"].astype(str), comments["comment_type"].astype(str)))
            if comments is not None else {}
        )

        ui.evidence_explorer(
            "upload",
            result["sources"],
            result["answer"],
            topic_name=names[topic_id],
            comment_types=comment_types,
            base_dir=BASE_DIR,
            video_path=upload.get("files", {}).get("video"),
            heading_for=lambda source: (
                f"{source['reference']} — {source['modality']} — {source['source_id']}"
            ),
            columns=3,
            notes_key="up_review_notes",
        )
    elif all(error for _t, _n, _r, error in topics):
        st.info("The evidence appears here once a topic report has been generated. Use Retry above.")
    else:
        st.info("No evidence was found for this report. Try a different topic or add more materials.")

    # ---- actions ----
    with st.container(horizontal=True, vertical_alignment="center", gap="small", key="up_actions"):
        st.download_button(
            "Download report (.md)",
            data=report_markdown(upload, report),
            file_name=f"course_report_{upload['upload_id']}.md",
            mime="text/markdown",
            key="up_download",
            type="primary",
        )
        st.button("Start new upload", key="up_reset", on_click=_ask_reset)

    if st.session_state.get("up_confirm_reset"):
        with st.container(key="up_reset_confirm"):
            st.warning(
                "Start a new upload? This deletes the uploaded files and their search index "
                "(saved educator reviews are kept)."
            )

            with st.container(horizontal=True, key="up_reset_buttons"):
                st.button("Yes, delete and start over", key="up_reset_yes", type="primary",
                          on_click=_reset_upload)
                st.button("Cancel", key="up_reset_no", on_click=_cancel_reset)

    _render_review_form(upload, report, user, user_can_review)
