def _run_processing(pending):
    files, options = pending["files"], pending["options"]
    planned = _planned_steps(files, options)
    labels = dict(PROCESS_STEPS)

    if files.get("transcript"):
        labels["transcript"] = "Reading the uploaded transcript (no transcription needed)"

    with st.status("Processing your course materials…", expanded=True) as status:
        lines = {step: st.empty() for step, _ in PROCESS_STEPS}
        bar = st.progress(0.0, text="Starting…")
        done = {"save"}
        state = {"current": None, "fraction": 0.0}

        def draw(step, kind, detail=""):
            icons = {"todo": "○", "running": "⏳", "done": "✓", "skipped": "—", "error": "✗"}
            text = labels[step] + (" — skipped" if kind == "skipped" else "")
            lines[step].markdown(_step_line(icons[kind], text, detail, kind), unsafe_allow_html=True)

        for step, _ in PROCESS_STEPS:
            draw(step, "todo" if planned[step] else "skipped")

        draw("save", "done", f"{pending['saved']} file{'s' if pending['saved'] != 1 else ''} saved")
        total = sum(planned.values())

        def progress(stage, fraction, message):
            step = STAGE_TO_STEP.get(stage)

            if step is None:
                return

            if state["current"] not in (None, step):
                done.add(state["current"])
                draw(state["current"], "done")

            state["current"], state["fraction"] = step, fraction
            draw(step, "done" if fraction >= 1 else "running", message)

            if fraction >= 1:
                done.add(step)

            overall = (len(done) + (0 if fraction >= 1 else fraction)) / total
            bar.progress(min(1.0, overall), text=f"{labels[step].split(' (')[0]}: {message}")

        try:
            manifest = up.process_upload(pending["upload_id"], files, options, progress)
        except up.UploadValidationError as error:
            failed = state["current"] or "save"
            draw(failed, "error", "failed")
            status.update(label=f"Processing failed at: {labels[failed]}", state="error", expanded=True)
            st.session_state["up_error"] = {"step": labels[failed], "errors": error.errors}
            return None
        except Exception as error:  # surfaced to the educator with a Retry button
            failed = state["current"] or "save"
            draw(failed, "error", "failed")
            status.update(label=f"Processing failed at: {labels[failed]}", state="error", expanded=True)
            st.session_state["up_error"] = {"step": labels[failed], "errors": [str(error)]}
            return None

        for step, _ in PROCESS_STEPS:
            if planned[step]:
                draw(step, "done")

        bar.progress(1.0, text="Done")
        status.update(label="Course materials processed", state="complete", expanded=False)

    st.session_state["upload"] = {
        "upload_id": pending["upload_id"],
        "manifest": manifest,
        "summary_df": up.load_summary(pending["upload_id"]),
        "files": files,
        "report": None,
    }
    st.session_state.pop("up_pending", None)
    st.session_state["up_step"] = 3
    return manifest


def _render_step_process():
    pending = st.session_state.get("up_pending")

    if pending and st.session_state.pop("up_run", False):
        if _run_processing(pending) is not None:
            _render_step_report()
            return

    error = st.session_state.get("up_error")

    if error:
        st.error(
            f"Processing failed at **{error['step']}**:\n\n"
            + "\n".join(f"- {message}" for message in error["errors"])
        )

        with st.container(horizontal=True, key="up_error_actions"):
            st.button("Retry", key="up_retry", type="primary", on_click=_retry_processing)
            st.button("← Back to files", key="up_back", on_click=_back_to_files)


