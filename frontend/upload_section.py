def _friendly_ai_error(error):
    """Plain-language version of a Gemini failure."""
    text = str(error)

    if "could not generate" in text.lower() or "503" in text or "unavailable" in text.lower():
        return ("Gemini is temporarily unavailable (it is overloaded or down). "
                "Wait a minute and press Retry.")

    if "GEMINI_API_KEY" in text:
        return "GEMINI_API_KEY is missing from .env. Add your Gemini API key to generate AI reports."

    if "citation" in text.lower():
        return "The AI answer cited evidence that does not exist, so it was rejected. Press Retry."

    return text


