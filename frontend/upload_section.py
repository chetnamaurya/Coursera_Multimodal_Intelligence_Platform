def _render_step_report():
    upload = st.session_state.get("upload")

    if not upload:
        st.info("Process your course materials first.")
        return

    _render_processed_summary(upload)
    summary = upload["summary_df"]

    if summary is None or summary.empty:
        st.info(
            "AI reports are organised by quiz topic, so they need quiz results. "
            "Start a new upload that includes quiz_responses.csv."
        )
        return

    names = dict(zip(summary["topic_id"].astype(str), summary["topic_name"].astype(str)))
    st.session_state.setdefault("up_chips_scope", SCOPE_OVERVIEW)

    if st.session_state.get("up_report_topic") not in names:
        st.session_state["up_report_topic"] = str(summary.iloc[0]["topic_id"])

    scope = st.segmented_control("Report type", [SCOPE_OVERVIEW, SCOPE_TOPIC], required=True,
                                 key="up_chips_scope")

    if scope == SCOPE_TOPIC:
        topic_id = st.selectbox("Topic", list(names), format_func=lambda t: names[t], key="up_report_topic")
        question = st.text_area("Question", value=up.default_question(names[topic_id]), height=90,
                                key=f"up_question_{topic_id}")
    else:
        topic_id = None
        top = summary.sort_values("incorrect_rate_pct", ascending=False).head(3)
        st.text_area(
            "Question (asked for each topic)",
            value=up.default_question("<topic>"),
            height=90,
            disabled=True,
            key="up_question_overview",
        )
        st.caption("Topics: " + " · ".join(
            f"{row.topic_name} ({row.incorrect_rate_pct:.2f}%)" for row in top.itertuples()
        ))
        question = None

    if st.button("Generate AI report", key="up_generate", type="primary"):
        if not _gemini_ready():
            st.error("GEMINI_API_KEY is missing from .env. Add your Gemini API key to generate AI reports.")
            return

        if scope == SCOPE_TOPIC and not str(question or "").strip():
            st.warning("Please enter a question.")
            return

        try:
            with st.spinner("Generating your AI report… this can take a minute per topic."):
                if scope == SCOPE_TOPIC:
                    data = up.generate_upload_report(upload["upload_id"], summary, "topic",
                                                     topic_id=topic_id, question=question.strip())
                else:
                    data = up.generate_upload_report(upload["upload_id"], summary, "overview", top_n=3)
        except Exception as error:
            st.error(f"Unable to generate the report. {_friendly_ai_error(error)}")
            return

        upload["report"] = {
            "scope": scope,
            "data": data,
            "generated_at": datetime.now(timezone.utc).isoformat(),
        }
        st.session_state["up_wizard_open"] = False
        st.session_state["scroll_to"] = "upload-report"
        st.rerun()


