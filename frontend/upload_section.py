def _stepper(step):
    labels = ["Upload", "Process", "Report"]
    parts = []

    for number, label in enumerate(labels, start=1):
        state = "done" if number < step else ("active" if number == step else "todo")
        dot = "✓" if state == "done" else ("●" if state == "active" else "○")
        parts.append(f'<span class="up-step is-{state}"><span class="up-step-dot">{dot}</span>{label}</span>')

        if number < len(labels):
            parts.append(f'<span class="up-step-line{" is-done" if number < step else ""}"></span>')

    return f'<div class="up-stepper" id="upload-wizard">{"".join(parts)}</div>'


def _card_status(card):
    chosen = sum(len(_selected(kind)) for kind in card["kinds"])

    if chosen:
        csv_problems = any(
            (check := _csv_check(kind)) is not None and check[0]
            for kind in card["kinds"] if kind in CSV_KINDS
        )

        if csv_problems:
            return ui.badge("Check errors", "pink")

        return ui.badge(f"✓ {chosen} file{'s' if chosen != 1 else ''}", "green")

    return ui.badge("Required", "yellow") if card["need"] == "required" else ui.badge("Optional", "outline")


def _render_card(card):
    with st.container(key=f"up_card_{card['id']}"):
        ui.render(
            '<div class="up-card-head">'
            f'<span class="up-card-icon" style="background:{card["color"]}">{ui._esc(card["icon"])}</span>'
            f'<div class="up-card-text"><div class="up-card-title">{ui._esc(card["title"])}</div>'
            f'<div class="up-card-accept">{ui._esc(card["accepts"])}</div></div>'
            f"{_card_status(card)}</div>"
        )

        if card["id"] == "comments":
            st.caption("Quiz results or learner comments are required, plus one more material.")

        for kind in card["kinds"]:
            label, types, multiple = UPLOADERS[kind]
            st.file_uploader(label, type=types, accept_multiple_files=multiple, key=_uploader_key(kind))
            chosen = _selected(kind)

            if chosen:
                origin = chosen[0][0]
                rows = "".join(
                    f'<div class="up-file"><span>{ui._esc(name)}</span><span>{_size_label(size)}</span></div>'
                    for name, size in (_name_and_size(source) for source in chosen)
                )
                tag = '<div class="up-demo-tag">Demo file</div>' if origin == "demo" else ""
                ui.render(f'<div class="up-files">{tag}{rows}</div>')

            if kind in CSV_KINDS:
                check = _csv_check(kind)

                if check is not None:
                    errors, preview, row_count = check

                    if errors:
                        ui.render(
                            '<div class="up-errors"><b>Please fix:</b><ul>'
                            + "".join(f"<li>{ui._esc(error)}</li>" for error in errors)
                            + "</ul></div>"
                        )
                    else:
                        ui.render(f'<div class="up-valid">✓ Valid · {row_count:,} rows</div>')

                    if preview is not None:
                        with st.expander("Preview (5 rows)"):
                            st.dataframe(preview, hide_index=True, width="stretch")

                st.download_button(
                    "Download template",
                    data=_template_csv(kind),
                    file_name=f"{kind}_template.csv",
                    mime="text/csv",
                    key=f"up_tpl_{kind}",
                    type="tertiary",
                )

        if card["id"] == "images":
            st.checkbox("Also extract frames from the video", key="up_opt_extract")


