def _planned_steps(files, options):
    has_video = bool(files.get("video"))
    describe = options.get("describe_images") and (
        files.get("images") or (has_video and options.get("extract_frames"))
    )

    return {
        "save": True,
        "quiz_analytics": bool(files.get("quiz_responses")),
        "learner_comment": bool(files.get("student_comments")),
        "transcript": bool(files.get("transcript") or has_video),
        "extract_frames": bool(has_video and options.get("extract_frames")),
        "documents": bool(files.get("documents")),
        "describe": bool(describe),
        "index": True,
    }


