def _reset_upload():
    """Delete the upload (files + search index) and start over."""
    upload = st.session_state.get("upload")

    if upload:
        up.delete_upload(upload["upload_id"])

    keep = {"up_gen"}

    for key in [key for key in st.session_state.keys() if str(key).startswith("up_") and key not in keep]:
        del st.session_state[key]

    st.session_state.pop("upload", None)
    st.session_state["up_gen"] = _gen() + 1  # fresh, empty file uploaders
    st.session_state["up_wizard_open"] = True
    st.session_state["up_step"] = 1
    st.session_state["scroll_to"] = "upload-wizard"


