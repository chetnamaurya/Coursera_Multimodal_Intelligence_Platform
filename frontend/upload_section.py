def _selected(kind):
    """
    Files chosen for `kind`: uploaded files win; otherwise demo files when
    "Try with demo files" is on. Returns a list of ("upload", UploadedFile)
    or ("demo", Path).
    """
    value = st.session_state.get(_uploader_key(kind))
    uploaded = value if isinstance(value, list) else ([value] if value else [])

    if uploaded:
        return [("upload", item) for item in uploaded]

    if st.session_state.get("up_demo"):
        return [("demo", path) for path in _demo_files().get(kind, []) if Path(path).exists()]

    return []


def _name_and_size(source):
    origin, item = source

    if origin == "upload":
        return item.name, item.size

    return Path(item).name, Path(item).stat().st_size


def _size_label(size):
    for unit in ("B", "KB", "MB", "GB"):
        if size < 1024 or unit == "GB":
            return f"{size:.0f} {unit}" if unit == "B" else f"{size:.1f} {unit}"
        size /= 1024


def _csv_check(kind):
    """(errors, preview, rows) for the chosen CSV, cached per file."""
    chosen = _selected(kind)

    if not chosen:
        return None

    origin, item = chosen[0]
    cache_key = f"{kind}:{item.file_id}" if origin == "upload" else f"{kind}:{item}"
    cache = st.session_state.setdefault("up_csv_cache", {})

    if cache_key not in cache:
        try:
            frame = up.read_csv(io.BytesIO(item.getvalue()) if origin == "upload" else item)
            cache[cache_key] = (up.validate_csv(frame, kind), frame.head(5), len(frame))
        except Exception as error:
            cache[cache_key] = ([f"Could not read this file as CSV ({error})."], None, 0)

    return cache[cache_key]


def _template_csv(kind):
    columns = up.REQUIRED_COLUMNS[kind]
    example = TEMPLATE_EXAMPLES[kind]
    return pd.DataFrame([example], columns=columns).to_csv(index=False)


def _readiness():
    """(ready, hint) for the Process button."""
    quiz, comments = _csv_check("quiz_responses"), _csv_check("student_comments")
    problems = []

    quiz_ok = quiz is not None and not quiz[0]
    comments_ok = comments is not None and not comments[0]

    if quiz is not None and quiz[0]:
        problems.append("fix the errors in the quiz results file")

    if comments is not None and comments[0]:
        problems.append("fix the errors in the learner comments file")

    present = set()

    if quiz_ok:
        present.add("quiz results")
    if comments_ok:
        present.add("learner comments")
    if _selected("video") or _selected("transcript"):
        present.add("lecture video")
    if _selected("documents"):
        present.add("course documents")
    if _selected("images"):
        present.add("screenshots")

    if not (quiz_ok or comments_ok):
        problems.append("add valid quiz results or learner comments")
    elif len(present) < 2:
        problems.append("add at least one more type of material (comments, video, documents or screenshots)")

    if problems:
        return False, "To continue, " + " and ".join(problems) + "."

    return True, f"Ready: {', '.join(sorted(present))}."


def _total_records(manifest):
    return sum(
        count for modality, count in manifest.get("counts", {}).items()
        if modality != "frames_extracted"
    )


